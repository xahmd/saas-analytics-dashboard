import { seriesFor, type Shape } from './series'

export type Unit = 'count' | 'percent' | 'days' | 'ms' | 'currency' | 'score'

export type Metric = {
  slug: string
  name: string
  group: string
  unit: Unit
  /** True when a falling line is good news (cancellations, latency…). */
  inverse?: boolean
  description: string
  owner: string
  table: string
  value: string
  time: string
  aggregation: 'Sum' | 'Average' | 'Count' | 'Median' | 'Ratio'
  dimensions: string[]
  shape: Shape
}

const drift = (base: number, growth: number, noise = 0.04, weekly = 0.06): Shape => ({
  kind: 'drift',
  base,
  growth,
  weekly,
  noise,
})

