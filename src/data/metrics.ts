export function dimensionValues(dimension: string) {
  return DIMENSION_VALUES[dimension] ?? ['Group A', 'Group B', 'Group C']
}

export function isAdditive(unit: Unit) {
  return unit === 'count' || unit === 'currency'
}

export function metricBySlug(slug: string | undefined) {
  return METRICS.find((m) => m.slug === slug)
}

export function pointsFor(metric: Metric) {
  return seriesFor(metric.slug, metric.shape)
}
